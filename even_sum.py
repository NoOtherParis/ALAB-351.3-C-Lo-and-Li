# even_sum.py
# Calculate the sum of even numbers from 1 to 50
# For loop and a while loop

even_sum = 0
 
for number in range(1, 51):
    if number % 2 == 0:
   
        even_sum = even_sum + number 
print(f"The sum of even numbers from 1 to 50 is {even_sum}.")

